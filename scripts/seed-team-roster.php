foreach ( $team_data as $member ) {
    $slug  = $member['slug'];
    $title = $member['name'];
    echo "\nProcessing: {$title} ({$slug})...\n";

    $existing = get_page_by_path( $slug, OBJECT, 'team_member' );

    $post_data = [
        'post_title'   => $title,
        'post_name'    => $slug,
        'post_status'  => 'publish',
        'post_type'    => 'team_member',
        'post_excerpt' => $member['subtitle'],
        'post_content' => $member['manifesto_p1'] . "\n\n" . $member['manifesto_p2'] . "\n\n" . $member['manifesto_p3'],
    ];

    if ( $existing ) {
        $post_id = $existing->ID;
        $post_data['ID'] = $post_id;
        wp_update_post( $post_data );
        echo "  -> Updated existing post ID: {$post_id}\n";
    } else {
        $post_id = wp_insert_post( $post_data );
        echo "  -> Created new post ID: {$post_id}\n";
    }

    if ( ! $post_id || is_wp_error( $post_id ) ) {
        echo "  [ERROR] Failed to save post for {$slug}\n";
        continue;
    }

    // Attach Portrait Image
    $portrait_file = $member['portrait'];
    $portrait_path = $upload_dir['basedir'] . '/2026/07/' . $portrait_file;
    if ( file_exists( $portrait_path ) ) {
        // Check if attachment exists
        $attachment = get_posts( [
            'post_type'   => 'attachment',
            'meta_key'    => '_wp_attached_file',
            'meta_value'  => '2026/07/' . $portrait_file,
            'numberposts' => 1,
        ] );

        if ( ! empty( $attachment ) ) {
            $attachment_id = $attachment[0]->ID;
        } else {
            $attachment_data = [
                'guid'           => $base_url . $portrait_file,
                'post_mime_type' => wp_check_filetype( $portrait_path )['type'],
                'post_title'     => $title . ' - پرتره رسمی',
                'post_content'   => '',
                'post_status'    => 'inherit',
            ];
            $attachment_id = wp_insert_attachment( $attachment_data, $portrait_path, $post_id );
            $metadata      = wp_generate_attachment_metadata( $attachment_id, $portrait_path );
            wp_update_attachment_metadata( $attachment_id, $metadata );
        }

        if ( $attachment_id ) {
            set_post_thumbnail( $post_id, $attachment_id );
            echo "  -> Assigned featured image attachment ID: {$attachment_id}\n";
        }
    }

    // Save All Custom Meta Fields
    update_post_meta( $post_id, '_md_member_role_badge', $member['role_badge'] );
    update_post_meta( $post_id, '_md_member_subtitle', $member['subtitle'] );
    update_post_meta( $post_id, '_md_member_org_hierarchy', $member['hierarchy'] );
    update_post_meta( $post_id, '_md_member_status_badge', $member['status_badge'] );
    update_post_meta( $post_id, '_md_member_photo_badge', $member['photo_badge'] );
    update_post_meta( $post_id, '_md_member_manifesto_p1', $member['manifesto_p1'] );
    update_post_meta( $post_id, '_md_member_manifesto_p2', $member['manifesto_p2'] );
    update_post_meta( $post_id, '_md_member_manifesto_p3', $member['manifesto_p3'] );
    update_post_meta( $post_id, '_md_metric_start_year', $member['start_year'] );

    // Metrics
    for ( $m_idx = 0; $m_idx < 4; $m_idx++ ) {
